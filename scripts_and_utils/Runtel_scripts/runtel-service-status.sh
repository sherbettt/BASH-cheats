#!/bin/bash

# Выход при ошибке (прерывает выполнение при любой ошибке)
set -e

# Определение цветов для оформления вывода
GREEN='\033[0;32m'   # Зеленый - для команд
BLUE='\033[0;34m'    # Синий - для заголовков
NC='\033[0m'         # No Color - сброс цвета

# Массив со списком всех сервисов для проверки
# Добавлен runtel-web-v2, который отсутствовал в первом списке
services=(
    runtel-cdr-v2
    runtel-core-v2
    runtel-event-hunter-v2
    runtel-iface-v2
    runtel-task-v2
    runtel-event-sender-v2
    runtel-web-v2
)

# ====================================================================
# 1. ПРОВЕРКА СТАТУСА СЕРВИСОВ
# ====================================================================
# Выводим текущий статус всех сервисов с подробной информацией
# ${services[@]/%/.service} - добавляет .service к каждому элементу массива
# -l  - полный вывод (без обрезания строк)
# --no-pager - отключает постраничный вывод (less)
# || true - игнорирует ошибку, если какой-то сервис не найден или остановлен
systemctl status "${services[@]/%/.service}" -l --no-pager || true
echo ""  # Пустая строка для разделения блоков

# ====================================================================
# 2. ПРОВЕРКА ВКЛЮЧЕНЫ ЛИ СЕРВИСЫ В АВТОЗАГРУЗКУ
# ====================================================================
# Цикл по всем сервисам из массива
for p in "${services[@]}"; do
    # Выводим команду зеленым цветом для наглядности
    echo -e "${GREEN}▶ systemctl is-enabled $p${NC}"
    # Проверяем включен ли сервис в автозагрузку
    # 2>/dev/null - скрываем ошибки (например, если сервис не найден)
    # || echo "disabled/not found" - выводим понятное сообщение при ошибке
    systemctl is-enabled "$p" 2>/dev/null || echo "disabled/not found"
done
echo ""  # Пустая строка для разделения блоков

# ====================================================================
# 3. ПРОВЕРКА ИНФОРМАЦИИ О ПАКЕТАХ
# ====================================================================
# Цикл по всем сервисам для получения информации о пакетах
for p in "${services[@]}"; do
    # Выводим команду зеленым цветом
    echo -e "${GREEN}▶ apt policy $p${NC}"
    # apt-cache policy - показывает информацию о версиях пакета
    # head -3 - выводим только первые 3 строки (самую важную информацию)
    # 2>/dev/null - скрываем ошибки, если пакет не найден
    # || echo "  not found" - выводим сообщение, если пакет отсутствует
    apt-cache policy "$p" 2>/dev/null | head -3 || echo "  not found"
    echo ""  # Пустая строка для разделения между пакетами
done

